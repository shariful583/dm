constexpr std::size_t kChunkSize = 16 * 1024;
constexpr std::uint64_t kDefaultSlowRate = 64 * 1024;
constexpr std::time_t kBaseLastModified = 1735689600; // 2025-01-01 00:00:00 UTC
constexpr std::string_view kSignedPrefix = "/signed";
constexpr std::string_view kSigningSecret = "lanes-test-secret";
constexpr const char *kNoAcceptRangesMarker = "X-Lanes-No-Accept-Ranges";

struct Resource {
  FileSpec spec;
  std::shared_ptr<const std::string> static_body; // non-null: served instead of generated bytes
  std::uint32_t generation = 0;

  std::uint64_t size() const { return static_body ? static_body->size() : spec.size; }

  void fill(std::uint64_t offset, std::span<char> out) const {
    if (static_body) {
      std::memcpy(out.data(), static_body->data() + offset, out.size());
    } else {
      fill_content(spec.seed, offset, out);
    }
  }
};

std::optional<std::string> param(const httplib::Request &req, const char *name) {
  if (!req.has_param(name)) {
    return std::nullopt;
  }
  return req.get_param_value(name);
}

std::uint64_t param_u64(const httplib::Request &req, const char *name, std::uint64_t fallback) {
  const auto value = param(req, name);
  if (!value) {
    return fallback;
  }
  std::uint64_t parsed = fallback;
  std::from_chars(value->data(), value->data() + value->size(), parsed);
  return parsed;
}

double param_double(const httplib::Request &req, const char *name, double fallback) {
  const auto value = param(req, name);
  return value ? std::strtod(value->c_str(), nullptr) : fallback;
}

std::string http_date(std::time_t t) {
  std::tm tm{};
#ifdef _WIN32
  gmtime_s(&tm, &t);
#else
  gmtime_r(&t, &tm);
#endif
  char buf[64];
  const auto n = std::strftime(buf, sizeof(buf), "%a, %d %b %Y %H:%M:%S GMT", &tm);
  return std::string(buf, n);
}

std::string percent_encode(std::string_view s) {
  static constexpr char kDigits[] = "0123456789ABCDEF";
  std::string out;
  for (const char c : s) {
    const auto b = static_cast<unsigned char>(c);
    if (std::isalnum(b) || c == '-' || c == '_' || c == '.' || c == '~' || c == '/') {
      out += c;
    } else {
      out += '%';
      out += kDigits[b >> 4];
      out += kDigits[b & 0x0F];
    }
  }
  return out;
}

std::string signature(std::string_view path, std::int64_t expires) {
  return hmac_sha256_hex(kSigningSecret, std::string(path) + "\n" + std::to_string(expires));
}

std::int64_t unix_now() {
  return std::chrono::duration_cast<std::chrono::seconds>(
             std::chrono::system_clock::now().time_since_epoch())
      .count();
}

// Counter key: path plus the full query, so differently configured URLs count separately.
std::string request_key(const std::string &path, const httplib::Request &req) {
  std::string key = path + "?";
  for (const auto &[name, value] : req.params) { // multimap: sorted by name
    key += name + "=" + value + "&";
  }
  return key;
}

void set_text(httplib::Response &res, int status, std::string text) {
  res.status = status;
  res.set_content(std::move(text) + "\n", "text/plain");
}

