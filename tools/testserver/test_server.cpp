struct TestServer::Impl {
  // How one body is sent; shared by every provider call of that response.
  struct BodyPlan {
    Resource resource;
    std::uint64_t rate = 0; // bytes/s, 0 = unlimited
    std::optional<std::uint64_t> drop_after;
    double drop_prob = 0;
    std::mt19937_64 rng;
    std::uint64_t sent = 0;
    std::chrono::steady_clock::time_point started{};
  };

  httplib::Server server;
  std::thread thread;
  int port = 0;
  std::atomic<bool> stopping{false};
  std::atomic<std::uint64_t> bytes_sent{0};

  mutable std::mutex mutex; // guards everything below
  std::map<std::string, Resource> resources;
  std::map<std::string, std::uint64_t> request_hits;
  std::map<std::string, std::uint64_t> body_hits;
  std::map<std::string, int> in_flight;
  std::set<std::pair<std::string, int>> connections;
  Stats stats;
  int concurrent_bodies = 0;

  void handle(const httplib::Request &req, httplib::Response &res);
  void handle_redirect(const httplib::Request &req, httplib::Response &res);
  bool stream(BodyPlan &plan, std::size_t offset, std::size_t length, httplib::DataSink &sink);
  bool sleep_until(std::chrono::steady_clock::time_point deadline) const;
};

void TestServer::Impl::handle(const httplib::Request &req, httplib::Response &res) {
  {
    std::lock_guard lock(mutex);
    ++stats.requests;
    connections.emplace(req.remote_addr, req.remote_port);
    stats.connections = connections.size();
  }

  if (const auto credentials = param(req, "basic_auth")) {
    if (req.get_header_value("Authorization") !=
        "Basic " + httplib::detail::base64_encode(*credentials)) {
      res.set_header("WWW-Authenticate", "Basic realm=\"lanes-test\"");
      set_text(res, 401, "login required");
      return;
    }
  }

  std::string path = req.path;
  if (path == "/redirect") {
    handle_redirect(req, res);
    return;
  }
  if (path == "/echo") {
    std::string body = "METHOD " + req.method + "\n";
    for (const auto &[name, value] : req.headers) {
      body += name + ": " + value + "\n";
    }
    body += "BODY " + req.body + "\n";
    res.status = 200;
    res.set_content(body, "text/plain");
    return;
  }
  if (path.starts_with(kSignedPrefix) && path.size() > kSignedPrefix.size() &&
      path[kSignedPrefix.size()] == '/') {
    path.erase(0, kSignedPrefix.size());
    const auto expires = param(req, "expires");
    const auto sig = param(req, "sig");
    std::int64_t expires_at = 0;
    if (!expires || !sig ||
        std::from_chars(expires->data(), expires->data() + expires->size(), expires_at).ec !=
            std::errc{} ||
        *sig != signature(path, expires_at)) {
      set_text(res, 403, "bad signature");
      return;
    }
    if (unix_now() >= expires_at) {
      set_text(res, 403, "link expired");
      return;
    }
  }

  const std::string key = request_key(path, req);
  std::uint64_t hit = 0;
  std::optional<Resource> found;
  {
    std::lock_guard lock(mutex);
    hit = request_hits[key]++;
    if (const auto it = resources.find(path); it != resources.end()) {
      found = it->second;
    }
  }

  if (const auto status = param_u64(req, "status", 0); status != 0) {
    const auto times = param_u64(req, "status_times", 1);
    if (times == 0 || hit < times) {
      if (const auto retry = param(req, "retry_after"); retry && (status == 429 || status == 503)) {
        res.set_header("Retry-After", *retry);
      }
      set_text(res, static_cast<int>(status), "injected status");
      return;
    }
  }

  if (!found) {
    set_text(res, 404, "not found");
    return;
  }
  const Resource &resource = *found;

  if (resource.spec.post_body) {
    if (req.method != "POST") {
      res.set_header("Allow", "POST");
      set_text(res, 405, "POST required");
      return;
    }
    if (req.body != *resource.spec.post_body) {
      set_text(res, 403, "wrong POST body");
      return;
    }
  } else if (req.method == "POST") {
    res.set_header("Allow", "GET, HEAD");
    set_text(res, 405, "POST not allowed");
    return;
  }

  const bool head = req.method == "HEAD";
  if (head && param_u64(req, "no_head", 0) != 0) {
    res.set_header("Allow", "GET");
    set_text(res, 405, "HEAD not allowed");
    return;
  }

  const bool no_range = param_u64(req, "no_range", 0) != 0;
  const bool chunked = param_u64(req, "chunked", 0) != 0;
  const std::string tag = resource.static_body ? std::to_string(std::hash<std::string>{}(path))
                                               : std::to_string(resource.spec.seed);
  res.set_header("ETag", "\"" + tag + "-" + std::to_string(resource.size()) + "-" +
                             std::to_string(resource.generation) + "\"");
  res.set_header("Last-Modified",
                 http_date(kBaseLastModified + std::time_t{86400} * resource.generation));
  if (!resource.spec.content_disposition.empty()) {
    res.set_header("Content-Disposition", resource.spec.content_disposition);
  }
  if (!no_range && !chunked && param_u64(req, "no_accept_ranges", 0) == 0) {
    res.set_header("Accept-Ranges", "bytes");
  } else {
    res.set_header(kNoAcceptRangesMarker, "1"); // see the post-routing handler
  }
  if (no_range) {
    res.status = 200; // explicit 200 stops httplib from applying the Range header
  }

  if (resource.size() == 0) {
    res.status = 200;
    res.set_content(std::string(), resource.spec.content_type);
    return;
  }

  auto plan = std::make_shared<BodyPlan>();
  plan->resource = resource;
  httplib::ContentProviderResourceReleaser releaser;

  if (!head) {
    std::uint64_t body_index = 0;
    {
      std::lock_guard lock(mutex);
      const auto max_conns = param_u64(req, "max_conns", 0);
      if (max_conns != 0 && static_cast<std::uint64_t>(in_flight[key]) >= max_conns) {
        res.set_header("Retry-After", "1");
        set_text(res, 503, "too many connections");
        return;
      }
      ++in_flight[key];
      stats.max_concurrent_bodies = std::max(stats.max_concurrent_bodies, ++concurrent_bodies);
      ++stats.body_responses;
      body_index = body_hits[key]++;
    }
    releaser = [this, key](bool) {
      std::lock_guard lock(mutex);
      --in_flight[key];
      --concurrent_bodies;
    };

    plan->rate = param_u64(req, "rate", 0);
    if (body_index < param_u64(req, "slow_requests", 0)) {
      plan->rate = param_u64(req, "slow_rate", kDefaultSlowRate);
    }
    if (const auto drop_after = param(req, "drop_after");
        drop_after && body_index < param_u64(req, "drop_times", 1)) {
      plan->drop_after = param_u64(req, "drop_after", 0);
    }
    plan->drop_prob = param_double(req, "drop_prob", 0.0);
    plan->rng.seed(param_u64(req, "seed", 1) * 1000003 + body_index);
  }

  if (chunked) {
    const auto size = resource.size();
    res.set_chunked_content_provider(
        resource.spec.content_type,
        [this, plan, size](std::size_t offset, httplib::DataSink &sink) {
          if (offset >= size) {
            sink.done();
            return true;
          }
          return stream(*plan, offset, static_cast<std::size_t>(size - offset), sink);
        },
        std::move(releaser));
    return;
  }

  res.set_content_provider(
      static_cast<std::size_t>(resource.size()), resource.spec.content_type,
      [this, plan](std::size_t offset, std::size_t length, httplib::DataSink &sink) {
        return stream(*plan, offset, length, sink);
      },
      std::move(releaser));
}

void TestServer::Impl::handle_redirect(const httplib::Request &req, httplib::Response &res) {
  const auto to = param(req, "to");
  if (!to || to->empty()) {
    set_text(res, 400, "redirect needs ?to=<path>");
    return;
  }
  const auto hops = param_u64(req, "hops", 1);
  if (hops > 1) {
    res.set_redirect("/redirect?to=" + percent_encode(*to) + "&hops=" + std::to_string(hops - 1));
  } else {
    const bool absolute = to->starts_with("http://") || to->starts_with("https://");
    res.set_redirect(absolute || to->front() == '/' ? *to : "/" + *to);
  }
}

bool TestServer::Impl::stream(BodyPlan &plan, std::size_t offset, std::size_t length,
                              httplib::DataSink &sink) {
  if (plan.started == std::chrono::steady_clock::time_point{}) {
    plan.started = std::chrono::steady_clock::now();
  }
  std::uniform_real_distribution<double> chance(0.0, 1.0);
  std::string buffer(kChunkSize, '\0');

  while (length > 0) {
    if (stopping) {
      return false;
    }
    std::size_t n = std::min(length, kChunkSize);
    if (plan.rate > 0) {
      // ~20 writes per second keeps throttled transfers smooth.
      n = std::min<std::size_t>(n, std::max<std::uint64_t>(1, plan.rate / 20));
    }
    if (plan.drop_after) {
      if (plan.sent >= *plan.drop_after) {
        return false;
      }
      n = std::min<std::size_t>(n, static_cast<std::size_t>(*plan.drop_after - plan.sent));
    }
    if (plan.drop_prob > 0 && chance(plan.rng) < plan.drop_prob) {
      return false;
    }

    plan.resource.fill(offset, std::span<char>(buffer.data(), n));
    // Counted before writing, so a client that has received the bytes always sees them in stats.
    bytes_sent += n;
    if (!sink.write(buffer.data(), n)) {
      return false;
    }
    plan.sent += n;
    offset += n;
    length -= n;

    if (plan.rate > 0) {
      const auto due = plan.started + std::chrono::microseconds(plan.sent * 1'000'000 / plan.rate);
      if (!sleep_until(due)) {
        return false;
      }
    }
  }
  return true;
}

bool TestServer::Impl::sleep_until(std::chrono::steady_clock::time_point deadline) const {
  constexpr auto kSlice = std::chrono::milliseconds(20);
  for (auto now = std::chrono::steady_clock::now(); now < deadline;
       now = std::chrono::steady_clock::now()) {
    if (stopping) {
      return false;
    }
    std::this_thread::sleep_for(
        std::min<std::chrono::steady_clock::duration>(deadline - now, kSlice));
  }
  return !stopping;
}

TestServer::TestServer() : impl_(std::make_unique<Impl>()) {}

TestServer::~TestServer() { stop(); }

void TestServer::start(int port) {
  auto &srv = impl_->server;
  // httplib takes ownership of the returned queue. 64 workers: one per open connection.
  srv.new_task_queue = [] { return new httplib::ThreadPool(64); };
  srv.set_keep_alive_max_count(100000);
  srv.set_keep_alive_timeout(30);
  srv.set_read_timeout(30);
  srv.set_write_timeout(30);

  const auto handler = [impl = impl_.get()](const httplib::Request &req, httplib::Response &res) {
    impl->handle(req, res);
  };
  srv.Get(R"(/.*)", handler);
  srv.Post(R"(/.*)", handler);
  // httplib adds "Accept-Ranges: bytes" to every HEAD response; undo that where the handler
  // asked for no Accept-Ranges header.
  srv.set_post_routing_handler([](const httplib::Request &, httplib::Response &res) {
    if (res.has_header(kNoAcceptRangesMarker)) {
      res.headers.erase(kNoAcceptRangesMarker);
      res.headers.erase("Accept-Ranges");
    }
  });

  const int bound = port == 0 ? srv.bind_to_any_port("127.0.0.1")
                              : (srv.bind_to_port("127.0.0.1", port) ? port : -1);
  if (bound <= 0) {
    throw std::runtime_error("test server: cannot bind 127.0.0.1:" + std::to_string(port));
  }
  impl_->port = bound;
  impl_->thread = std::thread([impl = impl_.get()] { impl->server.listen_after_bind(); });
  srv.wait_until_ready();
}

void TestServer::stop() {
  if (!impl_->thread.joinable()) {
    return;
  }
  impl_->stopping = true;
  impl_->server.stop();
  impl_->thread.join();
}

int TestServer::port() const { return impl_->port; }

std::string TestServer::url(std::string_view path) const {
  return "http://127.0.0.1:" + std::to_string(impl_->port) + std::string(path);
}

void TestServer::add_file(std::string path, FileSpec spec) {
  std::lock_guard lock(impl_->mutex);
  impl_->resources[std::move(path)] = Resource{std::move(spec), nullptr, 0};
}

void TestServer::add_static(std::string path, std::string body, std::string content_type) {
  Resource resource;
  resource.spec.content_type = std::move(content_type);
  resource.static_body = std::make_shared<const std::string>(std::move(body));
  std::lock_guard lock(impl_->mutex);
  impl_->resources[std::move(path)] = std::move(resource);
}

void TestServer::add_directory(const std::string &prefix, const std::filesystem::path &folder) {
  for (const auto &entry : std::filesystem::recursive_directory_iterator(folder)) {
    if (!entry.is_regular_file()) {
      continue;
    }
    std::ifstream in(entry.path(), std::ios::binary);
    std::string body((std::istreambuf_iterator<char>(in)), std::istreambuf_iterator<char>());
    std::string relative = std::filesystem::relative(entry.path(), folder).generic_string();
    const std::string ext = entry.path().extension().string();
    std::string type = "application/octet-stream";
    if (ext == ".m3u8") {
      type = "application/vnd.apple.mpegurl";
    } else if (ext == ".mpd") {
      type = "application/dash+xml";
    } else if (ext == ".ts") {
      type = "video/mp2t";
    } else if (ext == ".m4s") {
      type = "video/iso.segment";
    } else if (ext == ".mp4") {
      type = "video/mp4";
    }
    add_static(prefix + "/" + relative, std::move(body), type);
  }
}

void TestServer::add_hls_fixture(const std::string &prefix, const HlsFixture &fixture) {
  for (const auto &[rel, file] : fixture.files) {
    add_static(prefix + "/" + rel, file.body, file.content_type);
  }
}

void TestServer::change_content(const std::string &path, std::uint64_t new_seed,
                                std::optional<std::uint64_t> new_size) {
  std::lock_guard lock(impl_->mutex);
  const auto it = impl_->resources.find(path);
  if (it == impl_->resources.end() || it->second.static_body) {
    throw std::invalid_argument("change_content: no generated file at " + path);
  }
  it->second.spec.seed = new_seed;
  if (new_size) {
    it->second.spec.size = *new_size;
  }
  ++it->second.generation;
}

std::string TestServer::signed_url(std::string_view path, std::chrono::seconds ttl) const {
  const std::int64_t expires = unix_now() + ttl.count();
  return url(std::string(kSignedPrefix) + std::string(path)) +
         "?expires=" + std::to_string(expires) + "&sig=" + signature(path, expires);
}

Stats TestServer::stats() const {
  std::lock_guard lock(impl_->mutex);
  Stats s = impl_->stats;
  s.bytes_sent = impl_->bytes_sent;
  return s;
}

void TestServer::reset_stats() {
  std::lock_guard lock(impl_->mutex);
  impl_->stats = Stats{};
  impl_->connections.clear();
  impl_->bytes_sent = 0;
}

